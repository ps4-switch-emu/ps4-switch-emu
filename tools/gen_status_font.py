#!/usr/bin/env python3
"""Renders ASCII 32..126 of a TTF into an 8-bit alpha atlas for the PS4 status screen.

    python3 tools/gen_status_font.py <font.ttf> <pixel height> <out.h> [preview.png] [prefix]

prefix names the tables (default "Status": kStatusFontHeight, kStatusGlyphs, kStatusFontAlpha), so
several sizes can be included together.

Output: a C header with one glyph table (advance, bitmap offset, width) and the alpha bytes.
Runs inside the build container (Pillow is in its venv).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

font_path, size, out_path = sys.argv[1], int(sys.argv[2]), sys.argv[3]
preview_path = sys.argv[4] if len(sys.argv) > 4 and sys.argv[4] != "-" else None
prefix = sys.argv[5] if len(sys.argv) > 5 else "Status"
font = ImageFont.truetype(font_path, size)
ascent, descent = font.getmetrics()
cell_h = ascent + descent

glyphs, data = [], bytearray()
for code in range(32, 127):
    ch = chr(code)
    advance = int(round(font.getlength(ch)))
    left, _, right, _ = font.getbbox(ch)
    w = max(1, right - min(left, 0))
    img = Image.new("L", (w, cell_h), 0)
    ImageDraw.Draw(img).text((-min(left, 0), 0), ch, font=font, fill=255)
    glyphs.append((advance, len(data), w))
    data += img.tobytes()

with open(out_path, "w") as f:
    f.write(f"// Generated by tools/gen_status_font.py from {font_path.split('/')[-1]} at {size} px.\n")
    f.write("// Font: SIL Open Font License 1.1 (see the font's OFL.txt).\n#pragma once\n#include <stdint.h>\n\n")
    f.write(f"constexpr int k{prefix}FontHeight = {cell_h};\n")
    f.write("#ifndef STATUS_GLYPH_DEFINED\n#define STATUS_GLYPH_DEFINED\n")
    f.write("struct StatusGlyph { uint16_t advance; uint32_t offset; uint16_t width; };\n#endif\n")
    f.write(f"constexpr StatusGlyph k{prefix}Glyphs[95] = {{\n")
    for a, o, w in glyphs:
        f.write(f"    {{{a}, {o}, {w}}},\n")
    f.write(f"}};\nconstexpr uint8_t k{prefix}FontAlpha[] = {{\n")
    for i in range(0, len(data), 32):
        f.write("    " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
    f.write("};\n")

if preview_path:
    text = "PS4 Switch Emu - status 0123456789 [int 13706 KiB] main: running emulation (ok)"
    img = Image.new("RGB", (1400, cell_h * 2 + 20), (16, 24, 40))
    x = 10
    for ch in text:
        a, o, w = glyphs[ord(ch) - 32]
        glyph = Image.frombytes("L", (w, cell_h), bytes(data[o:o + w * cell_h]))
        img.paste((230, 235, 245), (x, 10), glyph)
        x += a
    img.save(preview_path)
print(f"{len(glyphs)} glyphs, cell height {cell_h}, {len(data)} bytes")
