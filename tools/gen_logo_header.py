#!/usr/bin/env python3
"""Turns the logo into eden/externals/ps4sup/status_logo.h for the launcher's header.

    tools/gen_logo_header.py <assets/icon.svg rendered as a 512x512 PNG> [size]

Render the SVG with any tool (rsvg-convert -w 512 -h 512, Inkscape, macOS qlmanage -t -s 512).
The square icon is scaled down and given the rounded corners of assets/logo.svg (radius 112/512),
then written as pixels in the launcher's framebuffer order with alpha in the top byte.
"""
import sys
from PIL import Image, ImageDraw

src, size = sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 64
big = Image.open(src).convert("RGB").resize((512, 512), Image.LANCZOS)
mask = Image.new("L", (512, 512), 0)
ImageDraw.Draw(mask).rounded_rectangle((0, 0, 511, 511), radius=112, fill=255)
img = big.convert("RGBA")
img.putalpha(mask)
img = img.resize((size, size), Image.LANCZOS)

words = []
pixels = img.get_flattened_data() if hasattr(img, "get_flattened_data") else img.getdata()
for r, g, b, a in pixels:
    words.append("0x%08Xu" % ((a << 24) | (b << 16) | (g << 8) | r))
lines = [", ".join(words[i:i + 8]) for i in range(0, len(words), 8)]
out = "eden/externals/ps4sup/status_logo.h"
with open(out, "w") as f:
    f.write("// SPDX-FileCopyrightText: Copyright 2026 PS4 Switch Emu\n")
    f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n\n")
    f.write("// Generated by tools/gen_logo_header.py from assets/icon.svg: the launcher's logo, %dx%d,\n" % (size, size))
    f.write("// framebuffer byte order with alpha in the top byte.\n\n#pragma once\n\n#include <cstdint>\n\n")
    f.write("constexpr int kLogoSize = %d;\n" % size)
    f.write("constexpr uint32_t kLogoPixels[kLogoSize * kLogoSize] = {\n    " + ",\n    ".join(lines) + "};\n")
print("wrote", out)
